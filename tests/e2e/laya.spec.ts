import {test,expect} from '@playwright/test';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {readFileSync} from 'node:fs';
const url=(name:string)=>process.env.MODEL_ATLAS_E2E_HTTP?`http://127.0.0.1:8765/build/laya-diagnosis/${name}`:pathToFileURL(resolve('build/laya-diagnosis',name)).href;
test('Laya 原快照明确告知只有未解析边界',async({page})=>{
 await page.goto(url('original-data.html'));await page.getByLabel('打开分析诊断').click();
 await expect(page.getByTestId('coverage-warning')).toContainText('分析覆盖不足');
 await expect(page.getByTestId('coverage-warning')).toContainText('可进入模块 0');
 await expect(page.locator('.offline-badge')).not.toContainText('教学 Decoder');
 await expect(page.getByRole('button',{name:'进入模块',exact:true})).toHaveCount(0);
});
test('Laya 默认主流程可读，计算细节可以完整恢复',async({page})=>{
 await page.goto(url('laya-reanalyzed.html'));
 const pane=page.locator('.pane').first(),graph=pane.locator('.graph');
 await pane.locator('.node-list>summary').click();
 await expect(pane.getByRole('button',{name:'主流程',exact:true})).toHaveAttribute('aria-pressed','true');
 await expect.poll(()=>graph.evaluate(el=>(el as any)._cyreg.cy.nodes().filter((n:any)=>!n.data('uiOnly')).length)).toBeLessThan(20);
 expect(await graph.evaluate(el=>(el as any)._cyreg.cy.edges().map((e:any)=>e.data('label')).some((s:string)=>s.includes('null')))).toBe(false);
 await expect.poll(()=>graph.evaluate(el=>(el as any)._cyreg.cy.edges().every((e:any)=>Boolean(e.data('routePoints'))))).toBe(true);
 const diagonals=await graph.evaluate(el=>{
  const cy=(el as any)._cyreg.cy;
  return cy.edges().filter((e:any)=>{
   const points=[e.sourceEndpoint(),...(e.segmentPoints()??[]),e.targetEndpoint()];
   return points.some((p:any,i:number)=>i>0&&Math.abs(p.x-points[i-1].x)>.1&&Math.abs(p.y-points[i-1].y)>.1);
  }).map((e:any)=>e.id());
 });
 expect(diagonals).toEqual([]);
 await expect(page.locator('.inspector')).toHaveCount(0);
 await expect(page.getByLabel('打开分析诊断')).toContainText('局部静态');
 await expect.poll(()=>graph.evaluate(el=>(el as any)._cyreg.cy.getElementById((el as any)._cyreg.cy.nodes().last().id()).position().y)).toBeGreaterThan(50);
 await page.screenshot({path:'build/laya-diagnosis/clean-overview.png',fullPage:true});
 await pane.getByRole('button',{name:'torch.stack([top2[:, 0], top2[:, 0] - top2[:, 1], ent, k / 255.0], -1)',exact:true}).click();
 await expect(page.locator('.group-members')).toContainText('仅合并展示');
 await page.getByRole('button',{name:'展开本组计算细节',exact:true}).click();
 const architecture=JSON.parse(readFileSync('build/laya-diagnosis/reanalyzed.architecture.json','utf8'));
 const original=architecture.nodes.filter((n:any)=>n.scope==='model').length;
 await expect.poll(()=>graph.evaluate(el=>(el as any)._cyreg.cy.nodes().filter((n:any)=>!n.data('uiOnly')).length)).toBe(original);
 await pane.getByRole('button',{name:'主流程',exact:true}).click();
 await expect.poll(()=>graph.evaluate(el=>(el as any)._cyreg.cy.nodes().filter((n:any)=>!n.data('uiOnly')).length)).toBeLessThan(20);
 await pane.getByRole('button',{name:'self.scorer',exact:true}).click();
 await page.getByRole('button',{name:'张量',exact:true}).click();
 await expect(page.locator('.inspector')).toContainText('形状未确定');
 await expect(page.locator('.inspector')).not.toContainText('[null]');
});
test('Laya 修复快照保留声明、顺序模块和两个返回值',async({page})=>{
 const errors:string[]=[],network:string[]=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/^https?:/.test(r.url())&&r.resourceType()!=='document')network.push(r.url());});
 await page.goto(url('laya-reanalyzed.html'));
 await page.getByLabel('打开分析诊断').click();await expect(page.getByTestId('coverage-warning')).toContainText('局部静态提取');
 await expect(page.getByTestId('coverage-warning')).toContainText('参数总数 未确认');
 await page.getByLabel('关闭分析诊断').click();
 await page.getByRole('button',{name:'声明 encoder',exact:true}).click();
 await expect(page.getByTestId('source')).toContainText('self.encoder = encoder');
 await expect(page.locator('.inspector')).toContainText('不代表已执行或已解析其内部');
 const pane=page.locator('.pane').first();await pane.locator('.node-list>summary').click();
 await expect(pane.getByRole('button',{name:'输出 logits',exact:true})).toBeVisible();
 await expect(pane.getByRole('button',{name:'输出 act_logits',exact:true})).toBeVisible();
 await pane.getByRole('button',{name:'self.scorer',exact:true}).click();
 await page.getByRole('button',{name:'进入模块',exact:true}).click();
 await expect(pane.getByRole('button',{name:'0: LayerNorm',exact:true})).toBeVisible();
 await expect(pane.getByRole('button',{name:'2: GELU',exact:true})).toBeVisible();
 await pane.getByRole('button',{name:'1: Linear',exact:true}).click();
 await page.getByRole('button',{name:'源码',exact:true}).click();
 await expect(page.getByTestId('source')).toContainText('nn.Linear(d, d)');
 await page.getByRole('button',{name:'张量',exact:true}).click();
 await expect(page.locator('.inspector')).toContainText('未知');
 await expect(page.locator('.offline-badge')).not.toContainText('教学 Decoder');
 await page.screenshot({path:'build/laya-diagnosis/reanalyzed-preview.png',fullPage:true});
 expect(errors).toEqual([]);expect(network).toEqual([]);
});
